import { existsSync, mkdirSync } from "node:fs";
import path from "node:path";

import { vendorFromGit } from "./vendor-git";
import type { AuxiliaryBundle, Replacement, VendorResult } from "./vendor-git";

export interface VendorOptions {
  /** Git URL of the upstream plugin to vendor */
  repoUrl: string;
  /** Commit SHA, tag, or branch to vendor */
  ref: string;
  /** Plugin entrypoint, relative to the repo root */
  entrypoint: string;
  /** Plugin namespace the preset enables rules */
  namespace: string;
  /** Sibling bundles the plugin spawns at runtime (e.g. a worker script) */
  auxiliary?: AuxiliaryBundle[];
  /**
   * find/replace pairs applied to the main bundle, e.g. to point a worker
   * reference at a namespaced auxiliary file
   */
  replacements?: Replacement[];
  /** Write nothing; throw if the vendored files are not byte-exact */
  checkOnly?: boolean;
}

export const buildVendor = ({
  repoUrl,
  ref,
  entrypoint,
  namespace,
  auxiliary,
  replacements,
  checkOnly = false,
}: VendorOptions): Promise<VendorResult> => {
  const resolvedOutDir = path.join(import.meta.dirname, "../tools/oxlint/config/vendors");
  if (!existsSync(resolvedOutDir)) mkdirSync(resolvedOutDir, { recursive: true });

  return vendorFromGit({
    banner: ({ commit }) => `// @ts-nocheck
// Vendored build of the plugin.
// Source: ${repoUrl} at commit ${commit}.
// Generated by scripts/build-vendors.ts — do not edit by hand.
`,
    auxiliary,
    checkOnly,
    entrypoint,
    replacements,
    installCommand: ["bun", "install"],
    outFile: path.join(resolvedOutDir, `${namespace}.ts`),
    ref,
    regenerateHint: "run `bun run scripts/build-vendors.ts`",
    repoUrl,
    rules: {
      configFile: path.join(import.meta.dirname, "../tools/oxlint/config/js-plugins/index.ts"),
      namespace,
    },
  });
};

type VendorBase = Omit<VendorOptions, "checkOnly">;

const parseArgs = (base: VendorBase): VendorOptions => {
  const args = process.argv.slice(2);
  const checkOnly = args.includes("--check");
  const positional = args.filter((arg) => arg !== "--check");
  if (positional.length > 1)
    throw new Error(`unexpected argument "${positional[1]}" (usage: [ref] [--check])`);

  return { ...base, checkOnly, ref: positional[0] ?? base.ref };
};

// Only run as a CLI when executed directly, so the function stays importable
if (import.meta.main) {
  const vendors: VendorBase[] = [
    {
      repoUrl: "https://github.com/dmmulroy/anti-slop.git",
      ref: "13909c9e07590f5a85d93c62712259fe14a883f7",
      entrypoint: "src/index.ts",
      namespace: "anti-slop",
    },
    {
      repoUrl: "https://github.com/jantimon/eslint-plugin-no-comment-slop.git",
      ref: "c38f7d691de1bff60da2f774a330f2a4a3cb3ff7",
      entrypoint: "src/index.ts",
      namespace: "no-comment-slop",
    },
    {
      repoUrl: "https://github.com/shadcn-ui/lint",
      ref: "529de36e185297a46ed5ef7049eb2965272d102e",
      entrypoint: "packages/lint/src/index.ts",
      namespace: "shadcn",
      /**
       * no-unknown-classes spawns a Tailwind worker next to the plugin. The
       * bundle is namespaced so it cannot collide with another vendor's worker
       * in the shared dist dir
       */
      auxiliary: [
        {
          entrypoint: "packages/lint/src/tailwind/worker.ts",
          fileName: "shadcn-tailwind-worker.ts",
        },
      ],
      /**
       * workerFile() looks the worker up as "tailwind-worker.js"; point that
       * reference at the namespaced bundle instead
       */
      replacements: [{ find: "tailwind-worker.js", replace: "shadcn-tailwind-worker.js" }],
    },
  ];

  try {
    await Promise.all(vendors.map((vendor) => buildVendor(parseArgs(vendor))));
  } catch (error) {
    console.error(`build-vendors: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
